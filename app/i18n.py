# Templates inherited from the first version of the application contain a large
# number of literal Russian labels.  The extension below turns every registered
# literal into a normal, request-time ``tr()`` call while Jinja tokenizes the
# template.  This keeps one template per page and also covers text, placeholders,
# titles and aria-labels.  New code may call ``tr()`` explicitly; both paths use
# this single catalogue.
class TemplateTranslationExtension(Extension):
    def __init__(self, environment):
        super().__init__(environment)
        phrases = sorted(TRANSLATIONS["kk"], key=len, reverse=True)
        alternatives = []
        for phrase in phrases:
            prefix = r"(?<!\w)" if phrase[0].isalnum() else ""
            suffix = r"(?!\w)" if phrase[-1].isalnum() else ""
            alternatives.append(prefix + re.escape(phrase) + suffix)
        self._literal_pattern = re.compile("|".join(alternatives))

    def filter_stream(self, stream):
        for token in stream:
            if token.type != "data" or not self._literal_pattern.search(token.value):
                yield token
                continue

            position = 0
            for match in self._literal_pattern.finditer(token.value):
                if match.start() > position:
                    yield Token(token.lineno, "data", token.value[position:match.start()])
                yield Token(token.lineno, "variable_begin", "{{")
                yield Token(token.lineno, "name", "tr")
                yield Token(token.lineno, "lparen", "(")
                yield Token(token.lineno, "string", match.group(0))
                yield Token(token.lineno, "rparen", ")")
                yield Token(token.lineno, "variable_end", "}}")
                position = match.end()
            if position < len(token.value):
                yield Token(token.lineno, "data", token.value[position:])


def current_language():
    if has_request_context() and current_user.is_authenticated:
        return current_user.language if current_user.language in {"ru", "kk"} else "ru"
    if has_request_context():
        return session.get("language", "ru") if session.get("language") in {"ru", "kk"} else "ru"
    return "ru"


def translate(value):
    if not isinstance(value, str) or current_language() != "kk":
        return value

    exact = TRANSLATIONS["kk"].get(value)
    if exact is not None:
        return exact

    dynamic_patterns = (
        (r"План на (\d+) год уже существует\.", r"\1 жылға арналған жоспар бұрыннан бар."),
        (r"Черновик плана на (\d+) год создан\.", r"\1 жылға арналған жоспар жобасы құрылды."),
        (r"Конфликт DOI разрешён\. Публикация №(\d+) оставлена\.", r"DOI қайшылығы шешілді. №\1 жарияланым қалдырылды."),
        (r"Публикация признана дубликатом публикации №(\d+) по результату проверки DOI\.", r"DOI тексеру нәтижесі бойынша жарияланым №\1 жарияланымның көшірмесі деп танылды."),
        (r"Обнаружены возможные дубликаты: публикации № (.+)\. Сначала необходимо разрешить конфликт монитором\.", r"Ықтимал көшірмелер табылды: № \1 жарияланымдар. Алдымен монитор қайшылықты шешуі керек."),
    )
    for pattern, replacement in dynamic_patterns:
        if re.fullmatch(pattern, value):
            return re.sub(pattern, replacement, value)
    return value


def localized_label(labels, code):
    return translate(labels.get(code, code))


def format_file_size(value):
    try:
        size = max(float(value), 0)
    except (TypeError, ValueError):
        return translate("Нет данных")

    units = ("Б", "КБ", "МБ", "ГБ", "ТБ")
    unit = units[0]
    for unit in units:
        if size < 1024 or unit == units[-1]:
            break
        size /= 1024
    precision = 0 if unit == "Б" else 1
    return f"{size:.{precision}f} {unit}"
